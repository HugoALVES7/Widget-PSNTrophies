#!/bin/bash
# Installs PSN Trophies (app + widget) on this Mac.
# Usage: bash install.sh             (detects your Apple account automatically)
#        bash install.sh ABCDE12345  (force a specific Team ID)
set -euo pipefail
cd "$(dirname "$0")"

# Messages in French if the Mac is in French, English otherwise.
if defaults read -g AppleLanguages 2>/dev/null | sed -n 2p | grep -q '"\{0,1\}fr'; then FR=1; else FR=0; fi
t() { if [ "$FR" = 1 ]; then printf "%s" "$2"; else printf "%s" "$1"; fi; }

step() { printf "\n\033[1;34m▸ %s\033[0m\n" "$1"; }
ok()   { printf "  \033[1;32m✓\033[0m %s\n" "$1"; }
fail() { printf "\n\033[1;31m✖ %s\033[0m\n\n" "$1"; exit 1; }

APP_NAME="PSNTrophies.app"
LOCAL_CONFIG="Config/Local.xcconfig"

# 1. Xcode -------------------------------------------------------------------
step "$(t "Checking Xcode" "Vérification de Xcode")"
[ -d /Applications/Xcode.app ] || fail "$(t \
  "Xcode is not installed. Install it from the App Store, open it once, then run this script again." \
  "Xcode n'est pas installé. Installe-le depuis l'App Store, ouvre-le une fois, puis relance ce script.")"
if [[ "$(xcode-select -p 2>/dev/null)" != *Xcode.app* ]]; then
  fail "$(t \
  "Your Mac is using the Command Line Tools instead of Xcode. Run this command (asks for your password), then run the script again:" \
  "Le Mac utilise les outils en ligne de commande au lieu de Xcode. Lance cette commande (mot de passe demandé), puis relance le script :")
   sudo xcode-select -s /Applications/Xcode.app"
fi
if ! xcodebuild -checkFirstLaunchStatus >/dev/null 2>&1; then
  fail "$(t \
  "Xcode isn't set up yet. Open Xcode once, accept the license and let it install its components, then run this script again." \
  "Xcode n'est pas encore configuré. Ouvre Xcode une fois, accepte la licence et laisse-le installer ses composants, puis relance ce script.")"
fi
ok "$(xcodebuild -version | head -1)"

# 2. Apple account (Team ID) -------------------------------------------------
step "$(t "Looking for your Apple developer account" "Recherche de ton compte développeur Apple")"
TEAM="${1:-}"
if [ -z "$TEAM" ] && [ -f "$LOCAL_CONFIG" ]; then
  TEAM="$(sed -n 's/^DEVELOPMENT_TEAM *= *//p' "$LOCAL_CONFIG" | tr -d '[:space:]')"
fi
if [ -z "$TEAM" ]; then
  # The Team ID is the OU field of the "Apple Development" certificate created by Xcode.
  TEAMS=""
  pem=""
  while IFS= read -r line; do
    pem+="$line"$'\n'
    if [[ "$line" == *"END CERTIFICATE"* ]]; then
      ou="$(printf "%s" "$pem" | openssl x509 -noout -subject -nameopt RFC2253 2>/dev/null \
            | tr ',' '\n' | sed -n 's/^OU=\([A-Z0-9]\{10\}\)$/\1/p' || true)"
      [ -n "$ou" ] && TEAMS+="$ou"$'\n'
      pem=""
    fi
  done < <(security find-certificate -a -c "Apple Development" -p 2>/dev/null || true)
  TEAMS="$(printf "%s" "$TEAMS" | sort -u | sed '/^$/d')"
  COUNT="$(printf "%s" "$TEAMS" | grep -c . || true)"
  if [ "$COUNT" = "0" ]; then
    fail "$(t \
    "No developer certificate found. In Xcode: Settings → Accounts → add your Apple ID,
   select your \"(Personal Team)\" → Manage Certificates… → + → Apple Development.
   Then run this script again. (See step 3 of the README.)" \
    "Aucun certificat de développeur trouvé. Dans Xcode : Réglages → Comptes → ajoute ton identifiant Apple,
   sélectionne ton équipe « (Personal Team) » → Gérer les certificats… → + → Apple Development.
   Puis relance ce script. (Détails dans le README, étape 3.)")"
  fi
  TEAM="$(printf "%s" "$TEAMS" | head -1)"
  if [ "$COUNT" != "1" ]; then
    printf "  %s\n%s\n  %s %s. %s\n" "$(t "Several teams found:" "Plusieurs équipes trouvées :")" "$TEAMS" \
      "$(t "Using" "J'utilise")" "$TEAM" "$(t "To pick another one: bash install.sh <TEAM_ID>" "Pour en choisir une autre : bash install.sh <TEAM_ID>")"
  fi
fi
ok "Team ID : $TEAM"

if [ ! -f "$LOCAL_CONFIG" ] || ! grep -q "DEVELOPMENT_TEAM *= *$TEAM" "$LOCAL_CONFIG"; then
  PREFIX="com.psntrophies.$(echo "$TEAM" | tr '[:upper:]' '[:lower:]')"
  cat > "$LOCAL_CONFIG" <<EOF
// Generated by install.sh — specific to this Mac, ignored by git.
DEVELOPMENT_TEAM = $TEAM
BUNDLE_ID_PREFIX = $PREFIX
EOF
  ok "$(t "Settings saved to" "Configuration enregistrée dans") $LOCAL_CONFIG"
fi

# 3. Build -------------------------------------------------------------------
step "$(t "Building (1–2 minutes the first time)" "Compilation (1 à 2 minutes la première fois)")"
LOG="build/install.log"
mkdir -p build
if ! xcodebuild -project PSNTrophies.xcodeproj -scheme PSNTrophies -configuration Release \
      -derivedDataPath build -allowProvisioningUpdates build >"$LOG" 2>&1; then
  grep -E "error:" "$LOG" | sed 's/^.*error: /  • /' | sort -u | head -8
  fail "$(t "The build failed (full log: $LOG). See Troubleshooting in the README." \
            "La compilation a échoué (journal complet : $LOG). Voir la section Dépannage du README.")"
fi
ok "$(t "Build succeeded" "Compilation réussie")"

# 4. Install -----------------------------------------------------------------
step "$(t "Installing into Applications" "Installation dans le dossier Applications")"
osascript -e 'tell application "System Events" to if exists process "PSNTrophies" then tell application "PSNTrophies" to quit' >/dev/null 2>&1 || true
sleep 1
rm -rf "/Applications/$APP_NAME"
ditto "build/Build/Products/Release/$APP_NAME" "/Applications/$APP_NAME"
pkill -f PSNTrophiesWidget 2>/dev/null || true
ok "$(t "Installed:" "Installé :") /Applications/$APP_NAME"

open "/Applications/$APP_NAME"
printf "\n\033[1;32m🏆 %s\033[0m %s\n" "$(t "Done!" "Terminé !")" \
  "$(t "The PSN Trophies app is open: connect your PlayStation account," "L'app Trophées PSN est ouverte : connecte ton compte PlayStation,")"
printf "   %s\n\n" "$(t "then right-click the desktop → Edit Widgets… → “PSN Trophies”." \
                     "puis clic droit sur le bureau → Modifier les widgets… → « Trophées PSN ».")"
